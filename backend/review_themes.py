_COMPILED = []
for t in THEMES:
    tid, neg_l, pos_l, neg, strong, pos, rec = t
    _COMPILED.append((tid, neg_l, pos_l,
                      re.compile(neg, re.I) if neg else None,
                      re.compile(strong, re.I) if strong else None,
                      re.compile(pos, re.I) if pos else None, rec))

_NEGATED_POS = re.compile(r"\bне\s+$", re.I)


def analyze(reviews: list, max_items: int = 6, min_hits: int = 2) -> dict | None:
    """reviews: [(rating, text, date)] → {pluses, minuses, recommendation}."""
    texts = [(int(r or 0), (t or "").replace("ё", "е").replace("Ё", "Е")) for r, t, *_ in reviews if t]
    n = len(texts)
    if n < 3:
        return None
    neg_hits: dict = {}
    pos_hits: dict = {}
    for rating, txt in texts:
        low = txt.lower()
        for tid, neg_l, pos_l, neg, strong, pos, rec in _COMPILED:
            if neg_l and neg is not None:
                if (rating <= 3 and neg.search(low)) or (strong is not None and strong.search(low)):
                    # «не скользят», «не промокают» — это плюс, а не минус
                    if not (pos is not None and pos.search(low) and rating >= 4):
                        neg_hits[tid] = neg_hits.get(tid, 0) + 1
                        continue
            if pos_l and pos is not None and rating >= 4 and pos.search(low):
                pos_hits[tid] = pos_hits.get(tid, 0) + 1
    labels = {t[0]: (t[1], t[2], t[6]) for t in THEMES}

    def top(hits, idx):
        out = [{"tag": labels[k][idx], "pct": round(v / n * 100), "count": v}
               for k, v in hits.items() if v >= min_hits and labels[k][idx]]
        out.sort(key=lambda x: (-x["count"], x["tag"]))
        return out[:max_items]

    minuses = top(neg_hits, 0)
    pluses = top(pos_hits, 1)
    recs = []
    for m in minuses[:3]:
        tid = next(k for k, v in labels.items() if v[0] == m["tag"])
        if labels[tid][2]:
            recs.append(labels[tid][2])
    rec = " ".join(recs) if recs else (
        "Существенных повторяющихся жалоб нет — товар можно масштабировать (реклама, акции)."
        if n >= 5 else "Отзывов пока мало для выводов.")
    return {"pluses": pluses, "minuses": minuses, "recommendation": rec,
            "method": "словарь тем", "texts": n}
